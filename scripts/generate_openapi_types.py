"""Generate the frontend TypeScript view of FastAPI's OpenAPI schemas."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "web" / "src" / "generated" / "openapi.ts"


def _literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _prop(name: str) -> str:
    if name.isidentifier():
        return name
    return _literal(name)


def _type(schema: dict[str, Any], indent: int = 0) -> str:
    if "$ref" in schema:
        return f'S["{schema["$ref"].rsplit("/", 1)[-1]}"]'
    if "const" in schema:
        return _literal(str(schema["const"]))
    if "enum" in schema:
        return " | ".join(_literal(str(item)) for item in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            variants = [_type(item, indent) for item in schema[key]]
            return " | ".join(dict.fromkeys(variants))
    if "allOf" in schema:
        return " & ".join(_type(item, indent) for item in schema["allOf"])

    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_type({**schema, "type": item}, indent) for item in kind)
    if kind == "array":
        return f"Array<{_type(schema.get('items') or {}, indent)}>"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties") or {}
        if not properties:
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                return f"Record<string, {_type(extra, indent)}>"
            return "Record<string, unknown>"
        required = set(schema.get("required") or [])
        lines = ["{"]
        for name, item in properties.items():
            optional = "" if name in required else "?"
            lines.append(f"{' ' * (indent + 2)}{_prop(name)}{optional}: {_type(item, indent + 2)};")
        lines.append(f"{' ' * indent}}}")
        return "\n".join(lines)
    if kind == "integer" or kind == "number":
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "null":
        return "null"
    return "unknown"


def build_types() -> str:
    from rag.api.app import create_app
    from rag.config.schema import Settings

    schemas = create_app(Settings()).openapi()["components"]["schemas"]
    lines = [
        "// Generated by scripts/generate_openapi_types.py. Do not edit by hand.",
        "",
        "export type S = {",
    ]
    for name in sorted(schemas):
        lines.append(f"  {_prop(name)}: {_type(schemas[name], 2)};")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    parser.add_argument("--stdout", action="store_true", help="print generated output")
    args = parser.parse_args()
    generated = build_types()
    if args.stdout:
        print(generated)
        return 0
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != generated:
            print(f"{TARGET} is stale; run python scripts/generate_openapi_types.py")
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
